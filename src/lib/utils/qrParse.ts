// src/lib/utils/qrParse.ts
// Parser untuk skema QR internal EPI:
//   Format lama (3 segmen): EPI:ITEM:<id> / EPI:LOC:<id> / EPI:BATCH:<id>
//   Format berparameter (4 segmen): EPI:SJ:<id>:<token> — Surat Jalan (Keputusan D1)
//                                    EPI:PJM:<id>:<token> — rental_order, Peminjaman External (F3, Bab 6.1)
//                                    EPI:SJI:<id>:<token> — sji_header, Surat Jalan Internal v2 Fase 2
//   EPI:SOP:<id> — sop_documents, QR di SOP cetak -> buka pembaca digital (R3, roadmap AI Training & SOP)
//   EPI:SO:<id> — so_customer, QR ditampilkan admin di /sales/po-verify (erp-epi-1) -> buka
//                 halaman unggah PO lapangan langsung ke SO yang tepat (R10, Sales B2B PO/RAP v2 §6)
//   EPI:COMP:<id> — component_unit (CLM v2), id integer > 0. Label dicetak admin erp-epi-1
//                   (/maintenance/komponen). Cermin dari VALID_TYPES di erp-epi-1/src/lib/utils/epiQr.js.
//   EPI:WSTN:<id>:<token> — master_workstation (rencana absensi istirahat v2), id integer.
//                           Dynamic Screen QR meja desk / stiker stasiun statis produksi.
//   EPI:BADGE:<no_badge>:<token> — kartu badge karyawan (rencana absensi istirahat v2, Fase 1
//                                  kiosk produksi). id = karyawan.no_badge, STRING (bukan integer).
//   EPI:SPK:<id>:<token> — spk (Kiosk Produksi Fase 3B, K3, 12 Sep 2026). Dicetak di lembar
//                          Work Sheet erp-epi-1 (printWorkSheet.js). Scan lewat scanner kiosk
//                          di kiosk/input-produksi memilih SPK ini otomatis (lihat handleHardwareScan).
//   EPI:SWA:<id>:<token> — sewa_masuk (Rencana Pertajam Rental Order v2 Fase 4, 18 Sep 2026).
//                          Sewa alat DARI vendor (rental_in) -- koleksi TERPISAH dari rental_order/
//                          PJM (Peminjaman External, arah berlawanan). Gate kedatangan/retur di
//                          api/sewa-masuk/gate.
// Prefix "EPI:" dipakai agar scanner bisa menolak barcode asing (mis. barcode
// bawaan supplier) secara aman dan jatuh ke pencarian manual.
//
// PENTING: format lama (3 segmen) WAJIB tetap diterima persis seperti sebelumnya —
// label ITEM/LOC/BATCH yang sudah tercetak fisik bergantung padanya (lihat Bab 6.1 rencana v2.0).

export type EpiQrType =
	| 'ITEM'
	| 'LOC'
	| 'BATCH'
	| 'SJ'
	| 'PJM'
	| 'SJI'
	// 4-Gate Retur Gudang v2 Fase 1 — dokumen retur_gudang (dicetak admin erp-epi).
	// Payload EPI:RTN:<id>:<token>, id integer > 0.
	| 'RTN'
	| 'SOP'
	| 'EQUIPMENT'
	| 'SO'
	| 'COMP'
	// Fase 5 — SJ Keluar Workshop (dicetak admin erp-epi-1, sjQrCode.js).
	// Payload EPI:CIK-SJK:<id>:<token> / EPI:BLJ-SJK:<id>:<token>.
	| 'CIK-SJK'
	| 'BLJ-SJK'
	// R7 (24 Sep 2026) — Gate Ketat v2 SJ Keluar Ciketing, chokepoint cetak server-side
	// baru (/print/ciketing-surat-jalan/[noSj], erp-epi). Prefix BARU (bukan CIK-SJK lama)
	// supaya QR fisik lama yang masih beredar tetap konsisten dengan flow read-only-nya,
	// sementara cetakan baru dapat flow serah-terima digital (bukan cuma tracking).
	// Payload EPI:CIK-SJK-V2:<id>:<token>, <id> = baris header grup (id terkecil per no_sj).
	| 'CIK-SJK-V2'
	// Fase 7 Unifikasi Workshop — padanan Balaraja: serah-terima digital SJ Keluar MB Balaraja.
	// Payload EPI:BLJ-SJK-V2:<id>:<token> (dicetak admin erp-epi, printBalarajaSuratJalanKeluar).
	| 'BLJ-SJK-V2'
	| 'WSTN'
	| 'BADGE'
	| 'SPK'
	| 'SWA';

export interface ParsedEpiQr {
	type: EpiQrType;
	id: number | string;
	token?: string; // Hanya ada untuk tipe berparameter (SJ, PJM, SJI, CIK-SJK, BLJ-SJK, WSTN, BADGE, SWA)
}

const VALID_TYPES: EpiQrType[] = ['ITEM', 'LOC', 'BATCH', 'SJ', 'PJM', 'SJI', 'RTN', 'SOP', 'EQUIPMENT', 'SO', 'COMP', 'CIK-SJK', 'BLJ-SJK', 'CIK-SJK-V2', 'BLJ-SJK-V2', 'WSTN', 'BADGE', 'SPK', 'SWA'];
// Tipe yang memakai format 4 segmen EPI:<TYPE>:<id>:<token>, id integer
const PARAMETERIZED_TYPES: EpiQrType[] = ['SJ', 'PJM', 'SJI', 'RTN', 'CIK-SJK', 'BLJ-SJK', 'CIK-SJK-V2', 'BLJ-SJK-V2', 'WSTN', 'SPK', 'SWA'];
// Tipe yang memakai format 4 segmen EPI:<TYPE>:<id>:<token>, id STRING (no_badge bukan selalu numerik)
const PARAMETERIZED_STRING_ID_TYPES: EpiQrType[] = ['BADGE'];

export function parseEpiQr(raw: string): ParsedEpiQr | null {
	if (!raw) return null;
	let codeStr = raw.trim();

	// Support URL-based QR codes generated by QrLabelPrint
	if (codeStr.includes('/scan/')) {
		const urlParts = codeStr.split('/scan/');
		codeStr = decodeURIComponent(urlParts[urlParts.length - 1]);
	}

	const parts = codeStr.split(':');
	if (parts[0] !== 'EPI') return null;
	const type = parts[1] as EpiQrType;
	if (!VALID_TYPES.includes(type)) return null;

	if (PARAMETERIZED_TYPES.includes(type)) {
		if (parts.length !== 4) return null;
		const id = Number(parts[2]);
		const token = parts[3];
		if (!Number.isFinite(id) || id <= 0 || !token) return null;
		return { type, id, token };
	}

	if (PARAMETERIZED_STRING_ID_TYPES.includes(type)) {
		if (parts.length !== 4) return null;
		const id = parts[2];
		const token = parts[3];
		if (!id || !token) return null;
		return { type, id, token };
	}

	if (type === 'EQUIPMENT') {
		if (parts.length < 3) return null;
		// EQUIPMENT id can contain special characters, so we join the rest of the parts
		const id = parts.slice(2).join(':');
		if (!id) return null;
		return { type, id };
	}

	// Format lama — tetap tepat 3 segmen, tanpa token
	if (parts.length !== 3) return null;
	const id = Number(parts[2]);
	if (!Number.isFinite(id) || id <= 0) return null;
	return { type, id };
}
